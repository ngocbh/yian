/**
 * A repo-level drift check, not a test of `src/`: `src/cli/bundled.ts` holds what `yian chat`
 * carries inside the CLI, so a binary needs no files beside it: the bundled flows
 * (`src/cli/flows/`), the `composing-agents` skill (`.claude/skills/composing-agents/`) and the
 * docs pages (`docs/src/content/docs/`). The test fails on any entry that differs from its file,
 * and on any extra or missing one; with `YIAN_UPDATE_BUNDLE=1` it writes the file again instead.
 */

import { expect, test } from "bun:test";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

import { DOCS, FLOWS, SKILL } from "../../src/cli/bundled.ts";
import { compareCodeUnits } from "../../src/diagnostics.ts";

const ROOT = fileURLToPath(new URL("../..", import.meta.url));
const UPDATE = process.env.YIAN_UPDATE_BUNDLE === "1";
const REGENERATE = "YIAN_UPDATE_BUNDLE=1 bun test tests/repo/bundled.test.ts";

/** Every file under `dir`, by its path relative to `dir` with `/` between parts, sorted. */
function filesUnder(dir: string): string[] {
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => relative(dir, join(entry.parentPath, entry.name)).split(sep).join("/"))
    .sort(compareCodeUnits);
}

/** The text of each file `names` picks under `dir`, keyed by `key` of its relative path. */
function texts(
  dir: string,
  names: readonly string[],
  key: (name: string) => string,
): Record<string, string> {
  return Object.fromEntries(
    names.map((name) => [key(name), readFileSync(join(dir, name), "utf8")]),
  );
}

/** What `bundled.ts` should hold, read from the files. */
function expected() {
  const flows = join(ROOT, "src", "cli", "flows");
  const skill = join(ROOT, ".claude", "skills", "composing-agents");
  const docs = join(ROOT, "docs", "src", "content", "docs");
  return {
    FLOWS: texts(
      flows,
      filesUnder(flows).filter((name) => name.endsWith(".yaml")),
      (name) => name,
    ),
    SKILL: texts(skill, filesUnder(skill), (name) => name),
    DOCS: texts(
      docs,
      filesUnder(docs).filter((name) => !name.includes("/") && name.endsWith(".md")),
      (name) => name.slice(0, -".md".length),
    ),
  };
}

/** The source of `src/cli/bundled.ts` holding `bundle`. */
function bundledModule(bundle: ReturnType<typeof expected>): string {
  const record = (entries: Record<string, string>) =>
    `{\n${Object.entries(entries)
      .map(([key, text]) => `  ${JSON.stringify(key)}:\n    ${JSON.stringify(text)},\n`)
      .join("")}}`;
  return (
    "/**\n" +
    " * What `yian chat` carries inside the CLI: its bundled flows (`src/cli/flows/`) by file " +
      "name, the\n" +
    " * `composing-agents` skill's files by path, and the docs pages by name. Generated by\n" +
    ` * \`${REGENERATE}\`; not edited by hand.\n` +
    " */\n\n" +
    `export const FLOWS: Readonly<Record<string, string>> = ${record(bundle.FLOWS)};\n\n` +
    `export const SKILL: Readonly<Record<string, string>> = ${record(bundle.SKILL)};\n\n` +
    `export const DOCS: Readonly<Record<string, string>> = ${record(bundle.DOCS)};\n`
  );
}

test("bundled.ts holds the flows, the composing-agents skill and the docs pages unchanged", () => {
  const bundle = expected();
  if (UPDATE) {
    writeFileSync(join(ROOT, "src", "cli", "bundled.ts"), bundledModule(bundle));
    return;
  }
  const held = { FLOWS, SKILL, DOCS };
  for (const name of ["FLOWS", "SKILL", "DOCS"] as const) {
    const want = bundle[name];
    const have = held[name];
    const stale = [
      ...Object.keys(want)
        .filter((key) => have[key] === undefined)
        .map((key) => `missing ${key}`),
      ...Object.keys(have)
        .filter((key) => want[key] === undefined)
        .map((key) => `extra ${key}`),
      ...Object.keys(want)
        .filter((key) => have[key] !== undefined && have[key] !== want[key])
        .map((key) => `changed ${key}`),
    ];
    expect(stale, `${name} is stale; run ${REGENERATE}`).toEqual([]);
  }
});

test("FLOWS holds the chat and the compaction it calls, and DOCS the cli page", () => {
  expect(Object.keys(FLOWS)).toEqual(["chat.yaml", "compact_history.yaml"]);
  expect(SKILL["SKILL.md"]).toContain("name: composing-agents");
  expect(SKILL["reference.md"]).toBeDefined();
  expect(DOCS["cli"]).toContain("yian chat");
});
